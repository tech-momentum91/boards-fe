/** Canonical filter-dropdown shape (module + status). */
export const SUPPORT_FEEDBACK_APPLIED_FILTER_DEFAULTS = {
  module: [],
  status: [],
};

export function mergeStoredSupportFeedbackFilters(stored) {
  const base = { ...SUPPORT_FEEDBACK_APPLIED_FILTER_DEFAULTS };
  if (!stored || typeof stored !== 'object') return base;
  return {
    ...base,
    module: Array.isArray(stored.module) ? stored.module : base.module,
    status: Array.isArray(stored.status) ? stored.status : base.status,
  };
}

